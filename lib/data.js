// detect card brand from the first digit(s) of a PAN
const cardBrand = (num) => {
  const n = (num || '').replace(/\D/g, '');
  if (/^4/.test(n)) return 'Visa';
  if (/^5[1-5]/.test(n) || /^2[2-7]/.test(n)) return 'Mastercard';
  if (/^(50|65|6)/.test(n)) return 'Verve';
  if (/^3[47]/.test(n)) return 'Amex';
  return 'Card';
};

